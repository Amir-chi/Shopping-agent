// No browser, network, model calls or dependencies: exercise the questionnaire state machine.
const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const context = vm.createContext({Intl,URLSearchParams,Date,Map,JSON,console,structuredClone,setTimeout,clearTimeout,setInterval:()=>0,
  location:{hash:'#outfits',protocol:'http:'},localStorage:{getItem:()=>null,setItem:()=>{}},navigator:{},
  document:{addEventListener:()=>{},querySelector:()=>null},window:{addEventListener:()=>{}}});
vm.runInContext(fs.readFileSync('catalog.js','utf8').replace(/initialize\(\);\s*$/, ''),context);
vm.runInContext(fs.readFileSync('shopping.js','utf8'),context);
const run=code=>vm.runInContext(code,context);
(async()=>{
  run("route='outfits';state.outfitSeed=null;let interviewCalls=[];api=async(path,params)=>{interviewCalls.push({path,params});return {items:[]};};");
  await run('loadRoute()');
  assert.equal(run('interviewCalls.length'),0,'no outfit or market fetch before answering');
  await run("actions['review-outfits']()");
  assert.equal(run('interviewCalls.length'),0,'no model review before answering');
  const opening=run('outfitsPage()');
  assert.ok(opening.includes('outfit-interview-form')&&!opening.includes('outfit-board'),'questions replace instant recommendations');
  assert.equal(run('outfitDraft().answers.audience'),'','old male default is not treated as a user answer');
  run('render=()=>{};let interviewNavigations=0;go=()=>{interviewNavigations++;return Promise.resolve();};');
  assert.equal(run('advanceOutfitInterview()'),false,'cannot skip required context');
  assert.equal(run('outfitDraft().step'),0);
  run("Object.assign(outfitDraft().answers,{audience:'women',occasion:'daily'});");
  assert.equal(run('advanceOutfitInterview()'),true);
  assert.equal(run('outfitDraft().step'),1);
  assert.ok(run('outfitsPage()').includes('مینیمال'));
  assert.equal(run('advanceOutfitInterview()'),false,'aesthetic must be explicitly answered');
  const second=run('outfitsPage()');
  assert.ok(second.includes('name="liked_colors"')&&second.includes('تنظیمات بیشتر')&&!second.includes('class="interview-more" open'),'colors, fit and shop conditions wait in a closed optional section');
  assert.ok(second.includes('ساخت ست')&&second.includes('مرحلهٔ ۲ از ۲'),'two steps, the second one builds the outfits');
  run("outfitDraft().answers.aesthetic='minimal';outfitDraft().answers.liked_colors=['آبی','سبز','کرم','مشکی']");
  assert.equal(run('advanceOutfitInterview()'),false,'at most three colors');
  run("outfitDraft().answers.liked_colors=['آبی'];actions['outfit-interview-back']()");
  assert.equal(run('outfitDraft().step'),0);
  assert.equal(run('outfitDraft().answers.liked_colors[0]'),'آبی','back preserves answers');
  run('advanceOutfitInterview()');
  assert.ok(run('outfitsPage()').includes('class="interview-more" open'),'chosen extras keep the optional section open');
  run("outfitDraft().answers.fit='relaxed';outfitDraft().answers.budget='1'");
  assert.equal(run('advanceOutfitInterview()'),false,'invalid budget cannot complete profile');
  run("outfitDraft().answers.budget='۵۰۰۰۰۰۰';outfitDraft().answers.multi=true");
  assert.equal(run('advanceOutfitInterview()'),true);
  assert.equal(run('interviewNavigations'),1,'only final submission loads outfits');
  assert.equal(run('state.outfitProfileV3'),true);
  assert.equal(run('state.outfitDraftV1'),null);
  assert.equal(run('outfitParams().liked_colors'),'آبی');
  assert.equal(run('outfitParams().aesthetic'),'minimal');
  assert.equal(run('outfitParams().fit'),'relaxed');
  assert.equal(run('outfitParams().budget'),'5000000');
  assert.equal(run('outfitParams().multi'),'1');
  await run('startOutfitInterview(false)');
  run("outfitDraft().answers.liked_colors=['قرمز']");
  assert.equal(run('state.outfitPrefs.liked_colors[0]'),'آبی','draft changes do not mutate applied answers');
  await run("actions['outfit-interview-cancel']()");
  assert.equal(run('state.outfitPrefs.liked_colors[0]'),'آبی','cancel retains prior profile');
  await run('startOutfitInterview(true)');
  assert.equal(run('outfitDraft().answers.audience'),'','start over does not silently reuse answers');
  assert.equal(run("outfitStyleAllowed('sporty','work')"),false);
  assert.equal(run("outfitStyleAllowed('classic','sport')"),false);
  run("state.outfitDraftV1={step:99,answers:null}");
  assert.equal(run('outfitDraft().step'),0,'malformed draft resets safely');
  run("state.outfitDraftV1={step:3,answers:{audience:'women',occasion:'daily',aesthetic:'',liked_colors:[],fit:'any',coverage:'any',season:'any',budget:'',shoes:true}}");
  assert.equal(run('outfitDraft().step'),1,'a draft from the old five-step form resumes at the last step');
  run("outfitDraft().answers.aesthetic='any'");
  assert.equal(run('advanceOutfitInterview()'),true,'with no colors chosen, color is simply free');
  console.log('Outfit interview: two steps, optional extras, gates, preferences, validation, back/edit/cancel, reset and API parameters passed.');
})().catch(error=>{console.error(error);process.exitCode=1;});
